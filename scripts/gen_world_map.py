"""Builds web/src/servers/worldMap.js from Natural Earth's 1:110m countries (public domain):
each country's outline as an SVG path in Web Mercator on a 1000 x 1000 square (latitudes cut at ±80),
keyed by its ISO 3166-1 alpha-2 code; and from its 1:50m countries, which have the small ones too
(Singapore, Hong Kong), each country's label point on the same square, where an address is pinned
when nothing nearer is known. Run with the GeoJSONs' paths:

    .venv/bin/python scripts/gen_world_map.py ne_110m_admin_0_countries.geojson ne_50m_admin_0_countries.geojson
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

SIZE = 1000
LIMIT = 80
OUT = Path(__file__).resolve().parent.parent / 'web/src/servers/worldMap.js'


def project(lon, lat):
    lat = max(-LIMIT, min(LIMIT, lat))
    x = (lon + 180) / 360 * SIZE
    y = (1 - math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)) / math.pi) / 2 * SIZE
    return round(x, 1), round(y, 1)


def ring(points):
    out, last = [], None
    for lon, lat in points:
        p = project(lon, lat)
        if p != last:
            out.append(p)
            last = p
    if len(out) < 3:
        return ''
    fmt = lambda v: ('%.1f' % v).rstrip('0').rstrip('.')  # noqa: E731
    return 'M' + 'L'.join(f'{fmt(x)} {fmt(y)}' for x, y in out) + 'Z'


def code_of(props):
    code = props.get('ISO_A2_EH') or props.get('ISO_A2')
    return code.upper() if code and code != '-99' and len(code) == 2 else ''


def main(source, points_source):
    data = json.loads(Path(source).read_text(encoding='utf-8'))
    shapes = {}
    for feature in data['features']:
        code = code_of(feature['properties'])
        if not code:
            continue
        geometry = feature['geometry']
        polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        path = ''.join(ring(poly[0]) for poly in polygons)
        if path:
            shapes[code] = shapes.get(code, '') + path
    places = {}
    for feature in json.loads(Path(points_source).read_text(encoding='utf-8'))['features']:
        props, code = feature['properties'], code_of(feature['properties'])
        if code and code not in places and props.get('LABEL_X') is not None and props.get('LABEL_Y') is not None:
            places[code] = project(props['LABEL_X'], props['LABEL_Y'])
    body = ',\n'.join(f'  {code}: {json.dumps(path)}' for code, path in sorted(shapes.items()))
    points = '\n'.join(' '.join(f'{code}: [{x:g}, {y:g}],' for code, (x, y) in sorted(places.items())[i:i + 8])
                       for i in range(0, len(places), 8))
    OUT.write_text('// Generated by scripts/gen_world_map.py from Natural Earth 1:110m countries (public domain): each\n'
                   f'// country as an SVG path in Web Mercator on a {SIZE} x {SIZE} square, latitudes cut at ±{LIMIT}; and\n'
                   '// from its 1:50m countries each one\'s label point [x, y] on that square. Do not edit.\n'
                   f'export const SIZE = {SIZE};\nexport const LIMIT = {LIMIT};\nexport const COUNTRIES = {{\n{body},\n}};\n'
                   f'export const PLACES = {{\n{points}\n}};\n', encoding='utf-8')
    print(f'{len(shapes)} countries, {len(places)} places, {OUT.stat().st_size} bytes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
